test_that("numeric vector", {
  # simulate data
  p <- simulate_project()
  s <- simulate_prioritization_settings(p)
  status <- sample.int(length(p$zones), p$dataset$get_n_pu(), replace = TRUE)
  status[c(2, 4)] <- NA_real_
  # create object
  x <- eval_prioritization(p, s, status)
  # run tests
  expect_type(x, "list")
  expect_type(x$summary, "list")
  expect_type(x$features, "list")
  expect_type(x$features$name, "list")
  expect_type(x$features$total, "list")
  expect_type(x$features$units, "list")
  expect_s3_class(x$features$held, "data.frame")
  expect_s3_class(x$features$locked, "data.frame")
  expect_true(assertthat::noNA(as.matrix(x$features$held)))
  expect_true(assertthat::noNA(as.matrix(x$features$locked)))
  expect_type(x$locks, "list")
  expect_type(x$locks$name, "list")
  expect_type(x$locks$total, "list")
  expect_type(x$locks$units, "list")
  expect_s3_class(x$locks$held, "data.frame")
  expect_s3_class(x$locks$locked, "data.frame")
  expect_true(assertthat::noNA(as.matrix(x$locks$held)))
  expect_true(assertthat::noNA(as.matrix(x$locks$locked)))
  expect_type(x$costs, "list")
  expect_type(x$costs$name, "list")
  expect_type(x$costs$total, "list")
  expect_type(x$costs$units, "list")
  expect_s3_class(x$costs$held, "data.frame")
  expect_s3_class(x$costs$locked, "data.frame")
  expect_true(assertthat::noNA(as.matrix(x$costs$held)))
  expect_true(assertthat::noNA(as.matrix(x$costs$locked)))
})

