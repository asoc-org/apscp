#' Solution provenance
#'
#' Create a [new_provenance()] object that indicates data were generated with
#' the tool.
#'
#' @return A [new_provenance()] object.
#'
#' @family method
#'
#' @examples
#' # create object
#' x <- solution_provenance()
#'
#' # print object
#' print(x)
#'
#' @export
solution_provenance <- function() {
  structure(
    list(
      name = "Solution",
      icon = "user",
      color = "black",
      description = "Generated with the tool using mathematical optimization.",
      url = ""
    ),
    class = "Provenance"
  )
}

