#' Contrast provenance
#'
#' Create a [new_provenance()] object that indicates data were generated
#' by contrasting two [new_solution()] objects.
#'
#' @param name1 `character` value indicating the name of a solution.
#'
#' @param name2 `character` value indicating the name of a solution.
#'
#' @inherit solution_provenance return
#'
#' @family method
#'
#' @examples
#' # create object
#' x <- contrast_provenance("sol1", "sol2")
#'
#' # print object
#' print(x)
#'
#' @export
contrast_provenance <- function(name1, name2) {
  assertthat::assert_that(
    assertthat::is.string(name1),
    assertthat::noNA(name1),
    assertthat::is.string(name2),
    assertthat::noNA(name2)
  )
  structure(
    list(
      name = "Contrast",
      icon = "user",
      color = "black",
      description = paste0(
        "Generated by comparing the \"", name1,
        "\" solution with the \"", name2, "\" solution."
      ),
      url = ""
    ),
    class = "Provenance"
  )
}

#' Heat map provenance
#'
#' Create a [new_provenance()] object that indicates data were generated
#' by comparing multiple solutions.
#'
#' @param zone `character` value indicating the zone name used to generate
#' the heat map.
#'
#' @param names `character` vector with the names of the solutions used
#' to generate the heat map.
#'
#' @inherit solution_provenance return
#'
#' @family method
#'
#' @examples
#' # create object
#' x <- heatmap_provenance("z1", c("sol1", "sol2", "sol3"))
#'
#' # print object
#' print(x)
#'
#' @export
heatmap_provenance <- function(zone, names) {
  assertthat::assert_that(
    assertthat::is.string(zone),
    assertthat::noNA(zone),
    is.character(names),
    length(names) > 0,
    assertthat::noNA(names)
  )
  structure(
    list(
      name = "Heatmap",
      icon = "user",
      color = "black",
      description = paste0(
        "Generated by calculating the number of planning units",
        "allocated to the \"", zone, "\" zone from the solutions:",
        paste(paste0("\"", names, "\""), collapse = ", "), "."
      ),
      url = ""
    ),
    class = "Provenance"
  )
}
